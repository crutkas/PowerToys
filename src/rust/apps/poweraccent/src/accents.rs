//! Accent character lookup tables.
//! Derived from PowerAccent.Core/Languages.cs (ALL language set).

/// Get accent characters for a given virtual key code.
pub fn get_accents(vk: u32) -> &'static [char] {
    match vk {
        // Numbers
        0x30 => &['₀', '⁰', '°'],
        0x31 => &['₁', '¹', '½', '⅓', '¼', '⅕', '⅙', '⅐', '⅛', '⅑', '⅒'],
        0x32 => &['₂', '²', '⅔', '⅖'],
        0x33 => &['₃', '³', '¾', '⅗', '⅜'],
        0x34 => &['₄', '⁴', '⅘'],
        0x35 => &['₅', '⁵', '⅚', '⅝'],
        0x36 => &['₆', '⁶'],
        0x37 => &['₇', '⁷', '⅞'],
        0x38 => &['₈', '⁸', '∞'],
        0x39 => &['₉', '⁹'],

        // Letters (VK_A = 0x41 through VK_Z = 0x5A)
        0x41 => &['à', 'á', 'â', 'ã', 'ä', 'å', 'æ', 'ā', 'ă', 'ą'],  // A
        0x42 => &['ḃ'],                                                    // B
        0x43 => &['ç', 'ć', 'ĉ', 'č', 'ċ', '©'],                        // C
        0x44 => &['ð', 'ď', 'đ', 'ḋ', 'ḍ'],                             // D
        0x45 => &['è', 'é', 'ê', 'ë', 'ē', 'ė', 'ę', 'ě'],             // E
        0x46 => &['ḟ'],                                                    // F
        0x47 => &['ĝ', 'ğ', 'ġ', 'ģ', 'ǧ'],                             // G
        0x48 => &['ĥ', 'ħ', 'ḣ'],                                        // H
        0x49 => &['ì', 'í', 'î', 'ï', 'ĩ', 'ī', 'ĭ', 'į', 'ı'],       // I
        0x4A => &['ĵ'],                                                    // J
        0x4B => &['ķ', 'ĸ'],                                              // K
        0x4C => &['ĺ', 'ļ', 'ľ', 'ŀ', 'ł'],                             // L
        0x4D => &['µ'],                                                    // M
        0x4E => &['ñ', 'ń', 'ņ', 'ň', 'ŉ', 'ŋ'],                       // N
        0x4F => &['ò', 'ó', 'ô', 'õ', 'ö', 'ø', 'ō', 'ŏ', 'ő', 'œ'],  // O
        0x50 => &['þ'],                                                    // P
        0x52 => &['ŕ', 'ŗ', 'ř'],                                        // R
        0x53 => &['ś', 'ŝ', 'ş', 'š', 'ß', 'ș'],                       // S
        0x54 => &['ţ', 'ť', 'ŧ', 'ț'],                                  // T
        0x55 => &['ù', 'ú', 'û', 'ü', 'ũ', 'ū', 'ŭ', 'ů', 'ű', 'ų'],  // U
        0x57 => &['ŵ'],                                                    // W
        0x59 => &['ý', 'ÿ', 'ŷ'],                                        // Y
        0x5A => &['ź', 'ż', 'ž'],                                        // Z

        _ => &[],
    }
}
